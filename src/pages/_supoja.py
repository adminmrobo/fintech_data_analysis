def apply(P):
    n = P['num']
    if P.get('kind', 'lesson') != 'lesson':
        return
    lv = {l['id']: l for l in P['levels']}
    if n in AIQ:
        P['quiz'].setdefault('lv3', []).append(AIQ[n])
    for (k, i), part in PARTS.items():
        if k == n and lv[i].get('math'):
            lv[i]['math']['parts'] = [part] + list(lv[i]['math']['parts'])
    for (k, i), m in MATH.items():
        if k == n and not lv[i].get('math'):
            m = dict(m); m['try'] = m.pop('try_'); lv[i]['math'] = m
    for (k, i, path), v in TEXT.items():
        if k == n:
            d = lv[i]
            ks = path.split('.')
            for x in ks[:-1]: d = d[x]
            d[ks[-1]] = v
